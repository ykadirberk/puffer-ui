"""Regenerate checked-in SPIR-V arrays; ordinary consumers need no compiler."""
from pathlib import Path
import os,shutil,subprocess,struct,hashlib,json
root=Path(__file__).resolve().parent.parent
compiler=shutil.which('glslangValidator') or str(Path(os.environ['VULKAN_SDK'])/'Bin/glslangValidator.exe')
out=root/'build-vulkan-shaders';out.mkdir(exist_ok=True)
parts=['// Generated by tools/compile_vulkan_shaders.py. Do not edit.','// Vulkan 1.3; no fast-math; source and compiler receipts beside sources.', '// Included by vulkan_draw.inl in the implementation namespace.', '// The first four lines form the amalgamation slice banner.']
receipt={'compiler':subprocess.check_output([compiler,'--version'],text=True),
         'command_flags':['-V','--target-env','vulkan1.3'], 'shaders':{}}
# Preserve the upstream Slug permission notice in distributed generated headers
# and their amalgamation, in addition to the original GLSL and installed notice.
slug_source=(root/'src/shaders/vulkan/harfbuzz_slug.glsl').read_text()
parts.append(slug_source[:slug_source.index('*/')+2])
sources=[root/f'src/shaders/vulkan/ui.{stage}' for stage in ['vert','frag']]
sources+=sorted((root/'src/shaders/vulkan').glob('sdf.*'))
sources+=sorted((root/'src/shaders/vulkan').glob('*.comp'))
receipt['includes']={p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted((root/'src/shaders/vulkan').glob('*.glsl'))}
for src in sources:
    stage=src.suffix[1:] if src.stem=='ui' else src.stem+'_'+src.suffix[1:] if src.stem=='sdf' else src.stem
    spv=out/(src.name+'.spv')
    flags=['-V','--target-env','vulkan1.3']
    # Vulkan 1.3's default SPIR-V 1.6 lowering of discard can introduce an
    # optional demote feature. OpKill in SPIR-V 1.5 needs no new borrowed-device
    # feature contract; keep this raster-mask shader within that baseline.
    if src.name=='sdf.frag': flags+=['--target-env','spirv1.5']
    subprocess.run([compiler,*flags,'-o',str(spv),str(src)],check=True)
    data=spv.read_bytes();words=struct.unpack('<'+'I'*(len(data)//4),data)
    symbol='vulkan_ui_'+stage if src.stem=='ui' else 'vulkan_'+stage
    parts.append(f'static constexpr u32 {symbol}[] = {{')
    for i in range(0,len(words),8):parts.append('    '+','.join(f'0x{x:08x}' for x in words[i:i+8])+',')
    parts.append('};')
    receipt['shaders'][stage]={'source_sha256':hashlib.sha256(src.read_bytes()).hexdigest(),'spirv_sha256':hashlib.sha256(data).hexdigest(),'command_flags':flags}
(root/'include/pufferui/impl/vulkan_shaders.inl').write_text('\n'.join(parts)+'\n')
(root/'src/shaders/vulkan/manifest.json').write_text(json.dumps(receipt,indent=2)+'\n')
