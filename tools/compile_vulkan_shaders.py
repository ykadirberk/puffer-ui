"""Regenerate checked-in SPIR-V arrays; ordinary consumers need no compiler."""
from pathlib import Path
import os,shutil,subprocess,struct,hashlib,json
root=Path(__file__).resolve().parent.parent
compiler=shutil.which('glslangValidator') or str(Path(os.environ['VULKAN_SDK'])/'Bin/glslangValidator.exe')
out=root/'build-vulkan-shaders';out.mkdir(exist_ok=True)
parts=['// Generated by tools/compile_vulkan_shaders.py. Do not edit.','// Vulkan 1.3; no fast-math; source and compiler receipts beside sources.', '// Included by vulkan_draw.inl in the implementation namespace.', '// The first four lines form the amalgamation slice banner.']
receipt={'compiler':subprocess.check_output([compiler,'--version'],text=True),
         'command_flags':['-V','--target-env','vulkan1.3'], 'shaders':{}}
for stage in ['vert','frag']:
    src=root/f'src/shaders/vulkan/ui.{stage}';spv=out/f'ui.{stage}.spv'
    subprocess.run([compiler,'-V','--target-env','vulkan1.3','-o',str(spv),str(src)],check=True)
    data=spv.read_bytes();words=struct.unpack('<'+'I'*(len(data)//4),data)
    parts.append(f'static constexpr u32 vulkan_ui_{stage}[] = {{')
    for i in range(0,len(words),8):parts.append('    '+','.join(f'0x{x:08x}' for x in words[i:i+8])+',')
    parts.append('};')
    receipt['shaders'][stage]={'source_sha256':hashlib.sha256(src.read_bytes()).hexdigest(),'spirv_sha256':hashlib.sha256(data).hexdigest()}
(root/'include/pufferui/impl/vulkan_shaders.inl').write_text('\n'.join(parts)+'\n')
(root/'src/shaders/vulkan/manifest.json').write_text(json.dumps(receipt,indent=2)+'\n')
